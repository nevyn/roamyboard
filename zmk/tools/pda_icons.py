SIZE = 16


def check():
    for name, rows in ICONS.items():
        if len(rows) != SIZE:
            sys.exit(f"{name}: {len(rows)} rows, expected {SIZE}")
        for i, row in enumerate(rows):
            if len(row) != SIZE or set(row) - set("#."):
                sys.exit(f"{name} row {i}: {row!r} must be {SIZE} of '#' and '.'")


def row_bits(row):
    return sum(1 << (SIZE - 1 - x) for x, c in enumerate(row) if c == "#")


def write_c(directory):
    names = list(ICONS)
    with open(os.path.join(directory, "icons.h"), "w") as h:
        h.write(
            "/*\n"
            " * The PDA home screen's app icons, generated by zmk/tools/pda_icons.py from its\n"
            " * pixel art: edit them there.\n"
            " *\n"
            " * SPDX-License-Identifier: MIT\n"
            " */\n\n"
            "#pragma once\n\n"
            "#include <stdint.h>\n\n"
            f"#define PDA_ICON_SIZE {SIZE}\n\n"
            "/** One icon: a row per element, bit 15 leftmost, a set bit lit. */\n"
            "struct pda_icon {\n"
            "    const char *name;\n"
            f"    uint16_t rows[{SIZE}];\n"
            "};\n\n"
            "extern const struct pda_icon pda_icons[];\n"
            "extern const int pda_icon_count;\n"
        )
    with open(os.path.join(directory, "icons.c"), "w") as c:
        c.write(
            "/*\n"
            " * Generated by zmk/tools/pda_icons.py; edit the pixel art there.\n"
            " *\n"
            " * SPDX-License-Identifier: MIT\n"
            " */\n\n"
            '#include "icons.h"\n\n'
            "const struct pda_icon pda_icons[] = {\n"
        )
        for name in names:
            values = [f"0x{row_bits(r):04X}" for r in ICONS[name]]
            c.write(f'    {{"{name}",\n     {{')
            for i in range(0, SIZE, 8):
                c.write(", ".join(values[i : i + 8]))
                c.write(",\n      " if i + 8 < SIZE else "}},\n")
        c.write("};\n")
        c.write("const int pda_icon_count = sizeof(pda_icons) / sizeof(pda_icons[0]);\n")


def write_png(path, scale=6, gap=4):
    names = list(ICONS)
    w = len(names) * (SIZE * scale + gap) - gap
    h = SIZE * scale
    rows = []
    for y in range(h):
        row = bytearray()
        for i, name in enumerate(names):
            art = ICONS[name][y // scale]
            row += bytes(255 if art[x // scale] == "#" else 0 for x in range(SIZE * scale))
            if i < len(names) - 1:
                row += bytes([128]) * gap
        rows.append(b"\0" + bytes(row))

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))

    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(b"".join(rows))))
        f.write(chunk(b"IEND", b""))


if __name__ == "__main__":
    check()
    here = os.path.dirname(os.path.abspath(__file__))
    write_c(os.path.join(here, "..", "src", "pda"))
    png = sys.argv[1] if len(sys.argv) > 1 else "/tmp/roamy-screen/icons.png"
    write_png(png)
    print(f"wrote icons.c, icons.h and {png}")
